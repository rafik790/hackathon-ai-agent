-- Resolution tracking: whether the failure of a TaskRun or PipelineRun has been worked on and fixed.
-- Independent of the Tekton execution status and of AI analyses and investigations; existing tables are not changed.
-- All timestamps are stored as TIMESTAMP WITH TIME ZONE and written in UTC.
-- The SQL is kept portable (PostgreSQL + H2 in PostgreSQL mode) so the same migrations back the test suite.

CREATE TABLE resolution_record (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type      VARCHAR(16)   NOT NULL,
    -- 'TASK_RUN:<id>' or 'PIPELINE_RUN:<id>': one record per run, also after the run row is gone.
    target_key       VARCHAR(48)   NOT NULL,
    task_run_id      BIGINT,
    -- For a TaskRun record: its PipelineRun, if known.
    pipeline_run_id  BIGINT,
    -- Copies of the run, so the record stays readable when the run is no longer collected.
    target_name      VARCHAR(253)  NOT NULL,
    namespace        VARCHAR(63)   NOT NULL,
    status           VARCHAR(16)   NOT NULL,
    assigned_team    VARCHAR(32),
    assigned_person  VARCHAR(128),
    summary          VARCHAR(2000),
    notes            VARCHAR(4000),
    updated_by       VARCHAR(128),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at      TIMESTAMP WITH TIME ZONE,
    -- Optimistic locking: an update must name the version it was based on.
    version          BIGINT        DEFAULT 0 NOT NULL,
    CONSTRAINT uk_resolution_record_target UNIQUE (target_key),
    -- Deleting a run keeps its resolution and history.
    CONSTRAINT fk_resolution_record_task_run FOREIGN KEY (task_run_id) REFERENCES task_run (id) ON DELETE SET NULL,
    CONSTRAINT fk_resolution_record_pipeline_run FOREIGN KEY (pipeline_run_id) REFERENCES pipeline_run (id) ON DELETE SET NULL,
    CONSTRAINT ck_resolution_record_target_type CHECK (target_type IN ('TASK_RUN', 'PIPELINE_RUN')),
    CONSTRAINT ck_resolution_record_status CHECK (status IN ('OPEN', 'INVESTIGATING', 'FIX_IN_PROGRESS', 'RESOLVED', 'REOPENED')),
    CONSTRAINT ck_resolution_record_team CHECK (assigned_team IS NULL
        OR assigned_team IN ('DEVELOPER', 'DEVOPS_PLATFORM', 'CICD_ENGINEER', 'UNKNOWN')),
    -- resolved_at is set exactly while the record is RESOLVED.
    CONSTRAINT ck_resolution_record_resolved CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL))
);

CREATE INDEX idx_resolution_record_task_run ON resolution_record (task_run_id);
CREATE INDEX idx_resolution_record_pipeline_run ON resolution_record (pipeline_run_id);

-- Append-only audit of every change of a record; never updated or deleted by the application.
CREATE TABLE resolution_history (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resolution_record_id  BIGINT        NOT NULL,
    -- Null for the change that created the record.
    previous_status       VARCHAR(16),
    new_status            VARCHAR(16)   NOT NULL,
    assigned_team         VARCHAR(32),
    assigned_person       VARCHAR(128),
    summary               VARCHAR(2000),
    note                  VARCHAR(4000),
    changed_by            VARCHAR(128),
    changed_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_resolution_history_record FOREIGN KEY (resolution_record_id) REFERENCES resolution_record (id),
    CONSTRAINT ck_resolution_history_previous CHECK (previous_status IS NULL
        OR previous_status IN ('OPEN', 'INVESTIGATING', 'FIX_IN_PROGRESS', 'RESOLVED', 'REOPENED')),
    CONSTRAINT ck_resolution_history_new CHECK (new_status IN ('OPEN', 'INVESTIGATING', 'FIX_IN_PROGRESS', 'RESOLVED', 'REOPENED'))
);

CREATE INDEX idx_resolution_history_record ON resolution_history (resolution_record_id, changed_at);
