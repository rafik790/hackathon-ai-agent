-- Phase 2.2 schema: AI-generated analysis of failure evidence.
-- All timestamps are stored as TIMESTAMP WITH TIME ZONE and written in UTC.
-- The SQL is kept portable (PostgreSQL + H2 in PostgreSQL mode) so the same migrations back the test suite.

-- One row per evidence, analysis version, prompt version and revision. Revisions above 0 are manual re-analyses.
CREATE TABLE failure_analysis (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    failure_evidence_id        BIGINT        NOT NULL,
    analysis_version           INTEGER       NOT NULL,
    prompt_version             VARCHAR(32)   NOT NULL,
    revision                   INTEGER       DEFAULT 0 NOT NULL,
    analysis_status            VARCHAR(16)   NOT NULL,
    failure_category           VARCHAR(64),
    severity                   VARCHAR(16),
    confidence                 NUMERIC(4, 3),
    summary                    VARCHAR(2000),
    root_cause                 VARCHAR(4000),
    observed_facts             JSONB,
    hypotheses                 JSONB,
    supporting_evidence        JSONB,
    recommended_actions        JSONB,
    preventive_recommendations JSONB,
    provider                   VARCHAR(32),
    model                      VARCHAR(128),
    input_tokens               INTEGER       DEFAULT 0 NOT NULL,
    output_tokens              INTEGER       DEFAULT 0 NOT NULL,
    processing_attempts        INTEGER       DEFAULT 0 NOT NULL,
    next_attempt_at            TIMESTAMP WITH TIME ZONE,
    started_at                 TIMESTAMP WITH TIME ZONE,
    locked_until               TIMESTAMP WITH TIME ZONE,
    claim_token                VARCHAR(36),
    last_error                 VARCHAR(4000),
    analysed_at                TIMESTAMP WITH TIME ZONE,
    created_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_failure_analysis_failure_evidence FOREIGN KEY (failure_evidence_id) REFERENCES failure_evidence (id) ON DELETE CASCADE,
    CONSTRAINT uk_failure_analysis_evidence_version UNIQUE (failure_evidence_id, analysis_version, prompt_version, revision),
    CONSTRAINT ck_failure_analysis_status CHECK (analysis_status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'RETRY_PENDING', 'FAILED')),
    CONSTRAINT ck_failure_analysis_severity CHECK (severity IS NULL OR severity IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_failure_analysis_confidence CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
    CONSTRAINT ck_failure_analysis_revision CHECK (revision >= 0),
    CONSTRAINT ck_failure_analysis_tokens CHECK (input_tokens >= 0 AND output_tokens >= 0),
    CONSTRAINT ck_failure_analysis_attempts CHECK (processing_attempts >= 0),
    CONSTRAINT ck_failure_analysis_processing CHECK (analysis_status <> 'PROCESSING'
        OR (claim_token IS NOT NULL AND locked_until IS NOT NULL)),
    CONSTRAINT ck_failure_analysis_retry CHECK (analysis_status <> 'RETRY_PENDING' OR next_attempt_at IS NOT NULL),
    -- An analysis can only be completed together with its result.
    CONSTRAINT ck_failure_analysis_completed CHECK (analysis_status <> 'COMPLETED'
        OR (failure_category IS NOT NULL AND severity IS NOT NULL AND confidence IS NOT NULL AND summary IS NOT NULL
            AND root_cause IS NOT NULL AND provider IS NOT NULL AND model IS NOT NULL AND analysed_at IS NOT NULL))
);

CREATE INDEX idx_failure_analysis_status_next_attempt_at ON failure_analysis (analysis_status, next_attempt_at);
CREATE INDEX idx_failure_analysis_category ON failure_analysis (failure_category);
CREATE INDEX idx_failure_analysis_severity ON failure_analysis (severity);
CREATE INDEX idx_failure_analysis_started_at ON failure_analysis (started_at);

-- Finds recently collected evidence that has no analysis yet.
CREATE INDEX idx_failure_evidence_status_collected_at ON failure_evidence (status, collected_at);
