-- Phase 1 schema: Tekton PipelineRun and TaskRun execution history.
-- All timestamps are stored as TIMESTAMP WITH TIME ZONE and written in UTC.
-- The SQL is kept portable (PostgreSQL + H2 in PostgreSQL mode) so the same migrations back the test suite.

CREATE TABLE pipeline_run (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_run_uid    VARCHAR(64)   NOT NULL,
    pipeline_run_name   VARCHAR(253)  NOT NULL,
    namespace           VARCHAR(63)   NOT NULL,
    pipeline_name       VARCHAR(253),
    status              VARCHAR(16)   NOT NULL,
    start_time          TIMESTAMP WITH TIME ZONE,
    completion_time     TIMESTAMP WITH TIME ZONE,
    duration_ms         BIGINT,
    failure_reason      VARCHAR(255),
    failure_message     VARCHAR(4000),
    resource_created_at TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_pipeline_run_uid UNIQUE (pipeline_run_uid),
    CONSTRAINT ck_pipeline_run_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED', 'UNKNOWN')),
    CONSTRAINT ck_pipeline_run_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

CREATE INDEX idx_pipeline_run_namespace ON pipeline_run (namespace);
CREATE INDEX idx_pipeline_run_pipeline_name ON pipeline_run (pipeline_name);
CREATE INDEX idx_pipeline_run_status ON pipeline_run (status);
CREATE INDEX idx_pipeline_run_start_time ON pipeline_run (start_time);
CREATE INDEX idx_pipeline_run_ns_name ON pipeline_run (namespace, pipeline_run_name);

CREATE TABLE task_run (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_run_uid        VARCHAR(64)   NOT NULL,
    task_run_name       VARCHAR(253)  NOT NULL,
    namespace           VARCHAR(63)   NOT NULL,
    pipeline_run_uid    VARCHAR(64),
    pipeline_run_name   VARCHAR(253),
    pipeline_name       VARCHAR(253),
    task_name           VARCHAR(253),
    status              VARCHAR(16)   NOT NULL,
    start_time          TIMESTAMP WITH TIME ZONE,
    completion_time     TIMESTAMP WITH TIME ZONE,
    duration_ms         BIGINT,
    failure_reason      VARCHAR(255),
    failure_message     VARCHAR(4000),
    resource_created_at TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_task_run_uid UNIQUE (task_run_uid),
    CONSTRAINT ck_task_run_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED', 'UNKNOWN')),
    CONSTRAINT ck_task_run_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

CREATE INDEX idx_task_run_namespace ON task_run (namespace);
CREATE INDEX idx_task_run_pipeline_name ON task_run (pipeline_name);
CREATE INDEX idx_task_run_status ON task_run (status);
CREATE INDEX idx_task_run_start_time ON task_run (start_time);
CREATE INDEX idx_task_run_pipeline_run_uid ON task_run (pipeline_run_uid);
CREATE INDEX idx_task_run_ns_pipeline_run_name ON task_run (namespace, pipeline_run_name);
