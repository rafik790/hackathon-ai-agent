-- Phase 2.2: database-backed quota of LLM provider invocations.
-- All timestamps are stored as TIMESTAMP WITH TIME ZONE and written in UTC.
-- The SQL is kept portable (PostgreSQL + H2 in PostgreSQL mode) so the same migrations back the test suite.

-- One row per provider. It is locked while a reservation is checked and recorded, so reservations are atomic.
CREATE TABLE ai_quota (
    provider   VARCHAR(32) PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- One row per reserved provider invocation, written before the provider is called and never given back.
CREATE TABLE ai_invocation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider            VARCHAR(32) NOT NULL,
    failure_analysis_id BIGINT,
    invoked_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ai_invocation_ai_quota FOREIGN KEY (provider) REFERENCES ai_quota (provider),
    -- Deleting an analysis must not free quota.
    CONSTRAINT fk_ai_invocation_failure_analysis FOREIGN KEY (failure_analysis_id) REFERENCES failure_analysis (id) ON DELETE SET NULL
);

CREATE INDEX idx_ai_invocation_provider_invoked_at ON ai_invocation (provider, invoked_at);
CREATE INDEX idx_ai_invocation_failure_analysis_id ON ai_invocation (failure_analysis_id);

-- Carries over what was counted before: one invocation per analysis, at its last attempt.
INSERT INTO ai_quota (provider, created_at)
SELECT DISTINCT provider, CURRENT_TIMESTAMP FROM failure_analysis
WHERE provider IS NOT NULL AND provider <> 'mock' AND started_at IS NOT NULL;

INSERT INTO ai_invocation (provider, failure_analysis_id, invoked_at)
SELECT provider, id, started_at FROM failure_analysis
WHERE provider IS NOT NULL AND provider <> 'mock' AND started_at IS NOT NULL;
