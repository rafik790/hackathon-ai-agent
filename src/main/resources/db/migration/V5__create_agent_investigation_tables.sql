-- Agent investigation (Phase 3.1): investigations of failed PipelineRuns and TaskRuns with read-only tools.
-- Independent of the failure-analysis tables; existing tables are not changed.
-- All timestamps are stored as TIMESTAMP WITH TIME ZONE and written in UTC.
-- The SQL is kept portable (PostgreSQL + H2 in PostgreSQL mode) so the same migrations back the test suite.

CREATE TABLE agent_investigation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type      VARCHAR(16)   NOT NULL,
    target_name      VARCHAR(253)  NOT NULL,
    namespace        VARCHAR(63)   NOT NULL,
    task_run_id      BIGINT,
    pipeline_run_id  BIGINT,
    status           VARCHAR(16)   NOT NULL,
    step_count       INTEGER       DEFAULT 0 NOT NULL,
    tool_call_count  INTEGER       DEFAULT 0 NOT NULL,
    summary          VARCHAR(2000),
    root_cause       VARCHAR(4000),
    failure_category VARCHAR(64),
    confidence       NUMERIC(4, 3),
    report           JSONB,
    error_message    VARCHAR(4000),
    provider         VARCHAR(32),
    model            VARCHAR(128),
    input_tokens     INTEGER       DEFAULT 0 NOT NULL,
    output_tokens    INTEGER       DEFAULT 0 NOT NULL,
    claim_token      VARCHAR(36),
    lease_until      TIMESTAMP WITH TIME ZONE,
    started_at       TIMESTAMP WITH TIME ZONE,
    completed_at     TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Deleting a run keeps its investigations.
    CONSTRAINT fk_agent_investigation_task_run FOREIGN KEY (task_run_id) REFERENCES task_run (id) ON DELETE SET NULL,
    CONSTRAINT fk_agent_investigation_pipeline_run FOREIGN KEY (pipeline_run_id) REFERENCES pipeline_run (id) ON DELETE SET NULL,
    CONSTRAINT ck_agent_investigation_target_type CHECK (target_type IN ('TASK_RUN', 'PIPELINE_RUN')),
    CONSTRAINT ck_agent_investigation_status CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_agent_investigation_counts CHECK (step_count >= 0 AND tool_call_count >= 0
        AND input_tokens >= 0 AND output_tokens >= 0),
    CONSTRAINT ck_agent_investigation_confidence CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
    -- A running investigation belongs to exactly one worker until its lease ends.
    CONSTRAINT ck_agent_investigation_running CHECK (status <> 'RUNNING' OR (claim_token IS NOT NULL AND lease_until IS NOT NULL))
);

CREATE INDEX idx_agent_investigation_status_created_at ON agent_investigation (status, created_at);
CREATE INDEX idx_agent_investigation_target ON agent_investigation (namespace, target_type, target_name);

-- One row per question to the model: the tool it chose (or its final report) and what happened.
CREATE TABLE agent_investigation_step (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investigation_id BIGINT        NOT NULL,
    step_number      INTEGER       NOT NULL,
    action           VARCHAR(16)   NOT NULL,
    tool_name        VARCHAR(64),
    arguments        JSONB,
    reasoning        VARCHAR(2000),
    status           VARCHAR(16)   NOT NULL,
    result_summary   VARCHAR(4000),
    error_message    VARCHAR(2000),
    duration_ms      BIGINT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_agent_investigation_step_investigation FOREIGN KEY (investigation_id)
        REFERENCES agent_investigation (id) ON DELETE CASCADE,
    CONSTRAINT uk_agent_investigation_step UNIQUE (investigation_id, step_number),
    CONSTRAINT ck_agent_investigation_step_action CHECK (action IN ('CALL_TOOL', 'FINAL_REPORT', 'INVALID')),
    CONSTRAINT ck_agent_investigation_step_status CHECK (status IN ('SUCCEEDED', 'FAILED', 'REJECTED', 'COMPLETED')),
    CONSTRAINT ck_agent_investigation_step_number CHECK (step_number >= 1)
);
