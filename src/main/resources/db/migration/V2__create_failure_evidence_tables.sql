-- Phase 2.1 schema: failure evidence (Pod, container and log details) for failed TaskRuns.
-- All timestamps are stored as TIMESTAMP WITH TIME ZONE and written in UTC.
-- The SQL is kept portable (PostgreSQL + H2 in PostgreSQL mode) so the same migrations back the test suite.
--
-- Evidence belongs to its parent row: foreign keys cascade on delete, so existing deletes of task_run rows
-- behave exactly as before. The unique constraints also index the foreign key columns.

-- One row per TaskRun attempt.
CREATE TABLE failure_evidence (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_run_id         BIGINT        NOT NULL,
    attempt             INTEGER       NOT NULL,
    pod_name            VARCHAR(253),
    pod_uid             VARCHAR(64),
    status              VARCHAR(32)   NOT NULL,
    pod_phase           VARCHAR(16),
    pod_reason          VARCHAR(255),
    pod_message         VARCHAR(4000),
    fetch_attempts      INTEGER       DEFAULT 0 NOT NULL,
    next_attempt_at     TIMESTAMP WITH TIME ZONE,
    last_error          VARCHAR(4000),
    collected_at        TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_failure_evidence_task_run FOREIGN KEY (task_run_id) REFERENCES task_run (id) ON DELETE CASCADE,
    CONSTRAINT uk_failure_evidence_task_run_attempt UNIQUE (task_run_id, attempt),
    CONSTRAINT ck_failure_evidence_attempt CHECK (attempt >= 0),
    CONSTRAINT ck_failure_evidence_fetch_attempts CHECK (fetch_attempts >= 0)
);

CREATE INDEX idx_failure_evidence_status_next_attempt_at ON failure_evidence (status, next_attempt_at);

-- One row per step, sidecar or init container of an attempt.
CREATE TABLE container_evidence (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id               BIGINT        NOT NULL,
    container_name            VARCHAR(253)  NOT NULL,
    container_type            VARCHAR(16)   NOT NULL,
    step_name                 VARCHAR(253),
    ordinal                   INTEGER,
    state                     VARCHAR(16),
    exit_code                 INTEGER,
    exit_code_source          VARCHAR(16),
    signal                    INTEGER,
    reason                    VARCHAR(255),
    tekton_termination_reason VARCHAR(255),
    message                   VARCHAR(4000),
    restart_count             INTEGER,
    started_at                TIMESTAMP WITH TIME ZONE,
    finished_at               TIMESTAMP WITH TIME ZONE,
    primary_failure           BOOLEAN       DEFAULT FALSE NOT NULL,
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_container_evidence_evidence FOREIGN KEY (evidence_id) REFERENCES failure_evidence (id) ON DELETE CASCADE,
    CONSTRAINT uk_container_evidence_evidence_container UNIQUE (evidence_id, container_name),
    CONSTRAINT ck_container_evidence_container_type CHECK (container_type IN ('STEP', 'SIDECAR', 'INIT')),
    CONSTRAINT ck_container_evidence_exit_code_source CHECK (exit_code_source IS NULL OR exit_code_source IN ('POD', 'TASKRUN', 'SYNTHETIC')),
    CONSTRAINT ck_container_evidence_restart_count CHECK (restart_count IS NULL OR restart_count >= 0)
);

-- One row per log stream: the current container instance or the previous (restarted) one.
CREATE TABLE container_log (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    container_evidence_id BIGINT        NOT NULL,
    previous              BOOLEAN       DEFAULT FALSE NOT NULL,
    status                VARCHAR(32)   NOT NULL,
    content               VARCHAR(65536),
    stored_bytes          INTEGER,
    truncated             BOOLEAN       DEFAULT FALSE NOT NULL,
    sha256                VARCHAR(64),
    redactions            INTEGER       DEFAULT 0 NOT NULL,
    fetched_at            TIMESTAMP WITH TIME ZONE,
    expires_at            TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_container_log_container_evidence FOREIGN KEY (container_evidence_id) REFERENCES container_evidence (id) ON DELETE CASCADE,
    CONSTRAINT uk_container_log_container_previous UNIQUE (container_evidence_id, previous),
    CONSTRAINT ck_container_log_stored_bytes CHECK (stored_bytes IS NULL OR stored_bytes >= 0),
    CONSTRAINT ck_container_log_redactions CHECK (redactions >= 0)
);

CREATE INDEX idx_container_log_expires_at ON container_log (expires_at);

-- Finds recently failed TaskRuns that still need evidence.
CREATE INDEX idx_task_run_status_completion_time ON task_run (status, completion_time);
